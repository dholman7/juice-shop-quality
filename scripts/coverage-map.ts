/**
 * Writes docs/coverage.md: every catalog endpoint against every role, and which tests cover it.
 * Built from test annotations in the last run, so it cannot claim coverage a test does not have.
 */
import { writeFileSync } from 'node:fs';
import { AREAS, ENDPOINTS, allows, type Area } from '../src/catalog';
import { ROLES } from '../src/config';
import { readRows, type Row } from './results';

/** How each result is written in a cell. */
const MARK: Record<Row['result'], string> = {
  passed: 'pass',
  failed: '**FAIL**',
  'known-bug': 'bug',
  flaky: 'flaky',
  skipped: 'skip',
  fixed: 'fixed?',
};

export function coverageMarkdown(rows: Row[]): string {
  const lines = [
    '# Coverage map',
    '',
    'Generated by `yarn coverage:map` from the last test run. Each cell shows the worst result among the tests that cover that endpoint as that role.',
    '',
    '`pass` behaves as intended · `bug` fails on an approved open bug (see known-bugs.json) · `**FAIL**` fails, not yet triaged · `skip` not run, see note · blank: not covered.',
    'In the "should" column, `✓` means the role may call the endpoint and `✗` means it must be refused; both are tested.',
    '',
  ];
  // Worst first: a cell shows the worst result among all tests for that endpoint and role.
  const rank: Row['result'][] = ['failed', 'fixed', 'flaky', 'known-bug', 'skipped', 'passed'];
  for (const area of Object.keys(AREAS) as Area[]) {
    lines.push(`## ${area} ${AREAS[area]}`, '', `| Endpoint | ${ROLES.join(' | ')} | Tests |`, `|:--|${ROLES.map(() => ':-:').join('|')}|--:|`);
    for (const ep of ENDPOINTS.filter((e) => e.area === area)) {
      const mine = rows.filter((r) => r.endpoint === ep.id);
      const cells = ROLES.map((role) => {
        const hits = mine.filter((r) => r.role === role);
        if (!hits.length) return '';
        const worst = rank.find((res) => hits.some((h) => h.result === res))!;
        return `${allows(ep, role) ? '✓' : '✗'} ${MARK[worst]}`;
      });
      lines.push(`| \`${ep.method} ${ep.path}\`${ep.note ? ` <sup title="${ep.note}">note</sup>` : ''} | ${cells.join(' | ')} | ${mine.length} |`);
    }
    lines.push('');
  }
  const notes = ENDPOINTS.filter((e) => e.note);
  if (notes.length) lines.push('## Notes', '', ...notes.map((e) => `- \`${e.method} ${e.path}\`: ${e.note}`), '');

  const ui = rows.filter((r) => r.project === 'ui');
  lines.push('## UI flows', '', '| Flow | Role | Result |', '|:--|:--|:--|');
  for (const r of ui) lines.push(`| ${r.title} | ${r.role ?? ''} | ${MARK[r.result]} |`);
  lines.push('');
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('docs/coverage.md', coverageMarkdown(readRows().rows));
  console.log('wrote docs/coverage.md');
}
